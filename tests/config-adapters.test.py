"""Config domains: generated adapters match config/defaults, ConfigFile loads them.

1. Every config/adapters/<Domain>Adapter.qml (generated by
   tools/config/gen_adapters.cjs) is instantiated offscreen and every key it
   declares, at any depth, is compared with config/defaults/<domain>.js: same
   key set, same value (after the QML type's conversion, so an `int` key with
   a fractional default would fail), and the declared type agrees with
   config/meta/AdapterTypes.js / the inference rules.
2. KeybindsAdapter carries every CoreBinds.js bind with its default combo and
   action, and the default custom binds.
3. ConfigFile.qml (one domain's FileView) is driven through a stub FileView:
   first load validates + marks ready, a missing file falls back to the
   defaults, a reload fills in missing top-level keys, adapter edits are
   written unless the store pauses auto-save.
4. The real Config.qml wires one ConfigFile per domain: once every file has
   loaded, initialLoadComplete flips and Config.<domain>.<key> reads the
   adapters (Quickshell types stubbed).
"""
