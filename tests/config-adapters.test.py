QML_TYPE = {"int": "int", "double": "real", "bool": "bool", "QString": "string",
            "QStringList": "list<string>", "QVariantList": "list<var>", "QVariant": "var"}


def infer(v):
    if isinstance(v, bool):
        return "bool"
    if isinstance(v, (int, float)):
        return "real"
    if isinstance(v, str):
        return "string"
    if isinstance(v, list):
        return "list<string>" if v and all(isinstance(x, str) for x in v) else "list<var>"
    return "JsonObject" if isinstance(v, dict) else "var"


def dump(obj):
    """{key: (qmlType, value)} of a QObject's own declared properties, recursively."""
    mo = obj.metaObject()
    res = {}
    for i in range(QObject.staticMetaObject.propertyCount(), mo.propertyCount()):
        p = mo.property(i)
        n, t = p.name(), p.typeName()
        if t.endswith("*"):
            res[n] = ("JsonObject", dump(h.eval(obj, n)))
        else:
            res[n] = (QML_TYPE.get(t, t), json.loads(h.eval(obj, f"JSON.stringify({n}) ?? 'null'")))
    return res


def same(a, b):
    if isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
        return float(a) == float(b)
    return a == b


adapters = REPO / "config/adapters"


def compare(tree, dflt, prefix, types, bad):
    """Append to `bad` every key/type/value of `tree` that differs from the defaults."""
    if set(tree) != set(dflt):
        bad.append(f"{prefix or '<root>'} keys differ: {sorted(set(tree) ^ set(dflt))}")
    for k in tree.keys() & dflt.keys():
        t, v = tree[k]
        p = prefix + k
        want = types.get(p) or infer(dflt[k])
        if t != want:
            bad.append(f"{p}: type {t}, want {want}")
        if t == "JsonObject":
            compare(v, dflt[k], p + ".", types, bad)
        elif not same(v, dflt[k]):
            bad.append(f"{p}: {json.dumps(v)[:60]} != default {json.dumps(dflt[k])[:60]}")


def load_adapter(name):
    # Same layout as the repo so the adapters' relative JS imports resolve.
    h.copy(f"config/adapters/{name}.qml", dest="config/adapters")
    return h.load(h.write(f"import QtQuick\n{name} {{}}", dest="config/adapters"), auto_stub=False)


for domain, defaults in sorted(ref["defaults"].items()):
    name = domain[0].upper() + domain[1:] + "Adapter"
    obj = load_adapter(name)
    types = ref["types"].get(domain, {})
    bad: list[str] = []
    compare(dump(obj), defaults, "", types, bad)
    check(not bad, f"{name}: every key/type/default matches config/defaults/{domain}.js" + (": " + "; ".join(bad[:5]) if bad else ""))

