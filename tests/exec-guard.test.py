"""The exec guard flags bare exec.Command in backend code and nothing else."""
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools" / "lint"))
import execguard  # noqa: E402

failures = []


def check(name, files, allow, want):
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        for rel, text in files.items():
            p = root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        got = len(execguard.scan(root, allow))
        if got != want:
            failures.append(f"{name}: want {want} findings, got {got}")


BARE = 'package x\nfunc f() { _ = exec.Command("ls").Run() }\n'
check("bare flagged", {"pkg/a.go": BARE}, {}, 1)
check("context ok", {"pkg/a.go": 'package x\nfunc f() { exec.CommandContext(ctx, "ls") }\n'}, {}, 0)
check("comment ignored", {"pkg/a.go": "package x\n// exec.Command(\"ls\") is banned\n"}, {}, 0)
check("test file skipped", {"pkg/a_test.go": BARE}, {}, 0)
check("vendor skipped", {"vendor/x/a.go": BARE}, {}, 0)
check("generated skipped", {"pkg/a.go": "// Code generated by x. DO NOT EDIT.\n" + BARE}, {}, 0)
check("allowlisted", {"pkg/a.go": BARE}, {"pkg/a.go": "reason"}, 0)

# The real tree must be clean.
real = execguard.scan()
if real:
    failures.append("backend has bare exec.Command: " + "; ".join(real[:3]))

if failures:
    print("\n".join(failures))
    sys.exit(1)
print("exec-guard: ok")
